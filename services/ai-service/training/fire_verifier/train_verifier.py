"""Train a lightweight MobileNetV3-Small Stage-2 fire context verifier and export to ONNX.

Expected dataset directory layout (generated by extract_crops.py):
  <data-dir>/
    train/
      false_alarm/
      real_fire/
    val/
      false_alarm/
      real_fire/

Output ONNX contract matches `app.services.fire_verifier.FireVerifier`:
  - Input:  `image` float32 [1, 3, 224, 224] (RGB, ImageNet mean/std normalized)
  - Output: `logits` float32 [1, 2] (`0=false_alarm`, `1=real_fire`)
"""

import argparse
import hashlib
import json
import logging
import time
from pathlib import Path
from typing import Any

import numpy as np
import onnxruntime as ort
import torch
from torch import nn
from torch.utils.data import DataLoader
from torchvision import datasets, models, transforms

LOGGER = logging.getLogger(__name__)
CLASS_TO_INDEX = {"false_alarm": 0, "real_fire": 1}
IMAGENET_MEAN = (0.485, 0.456, 0.406)
IMAGENET_STD = (0.229, 0.224, 0.225)


def sha256_file(path: Path) -> str:
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def build_loaders(
    data_dir: Path, batch_size: int
) -> tuple[DataLoader[Any], DataLoader[Any], torch.Tensor]:
    train_tf = transforms.Compose(
        [
            transforms.Resize((224, 224)),
            transforms.RandomHorizontalFlip(p=0.5),
            transforms.RandomAffine(degrees=10, translate=(0.06, 0.06), scale=(0.9, 1.1)),
            transforms.ColorJitter(brightness=0.15, contrast=0.15),
            transforms.ToTensor(),
            transforms.Normalize(IMAGENET_MEAN, IMAGENET_STD),
        ]
    )
    val_tf = transforms.Compose(
        [
            transforms.Resize((224, 224)),
            transforms.ToTensor(),
            transforms.Normalize(IMAGENET_MEAN, IMAGENET_STD),
        ]
    )
    train_ds = datasets.ImageFolder(str(data_dir / "train"), transform=train_tf)
    val_ds = datasets.ImageFolder(str(data_dir / "val"), transform=val_tf)
    if train_ds.class_to_idx != CLASS_TO_INDEX or val_ds.class_to_idx != CLASS_TO_INDEX:
        raise ValueError(
            f"Expected folders {CLASS_TO_INDEX}, got train={train_ds.class_to_idx} val={val_ds.class_to_idx}"
        )
    targets = np.array(train_ds.targets)
    counts = np.bincount(targets, minlength=2).astype(np.float32)
    weights = counts.sum() / np.maximum(counts * 2.0, 1.0)
    train_loader = DataLoader(train_ds, batch_size=batch_size, shuffle=True, num_workers=0)
    val_loader = DataLoader(val_ds, batch_size=batch_size, shuffle=False, num_workers=0)
    return train_loader, val_loader, torch.tensor(weights, dtype=torch.float32)


def build_model(pretrained: bool) -> nn.Module:
    weights = models.MobileNet_V3_Small_Weights.DEFAULT if pretrained else None
    model = models.mobilenet_v3_small(weights=weights)
    in_features = model.classifier[-1].in_features
    model.classifier[-1] = nn.Linear(in_features, 2)
    return model


@torch.no_grad()
def evaluate_probabilities(
    model: nn.Module, loader: DataLoader[Any], device: torch.device
) -> tuple[np.ndarray, np.ndarray]:
    model.eval()
    probs_all: list[np.ndarray] = []
    labels_all: list[np.ndarray] = []
    for images, labels in loader:
        logits = model(images.to(device))
        probs = torch.softmax(logits, dim=1)[:, 1].cpu().numpy()
        probs_all.append(probs)
        labels_all.append(labels.numpy())
    return np.concatenate(probs_all), np.concatenate(labels_all)


def metrics_at_threshold(
    probs: np.ndarray, labels: np.ndarray, threshold: float
) -> dict[str, float]:
    preds = (probs >= threshold).astype(np.int64)
    tp = int(((preds == 1) & (labels == 1)).sum())
    fp = int(((preds == 1) & (labels == 0)).sum())
    fn = int(((preds == 0) & (labels == 1)).sum())
    tn = int(((preds == 0) & (labels == 0)).sum())
    precision = tp / (tp + fp) if (tp + fp) else 0.0
    recall = tp / (tp + fn) if (tp + fn) else 0.0
    f1 = 2 * precision * recall / (precision + recall) if (precision + recall) else 0.0
    fpr = fp / (fp + tn) if (fp + tn) else 0.0
    return {
        "threshold": threshold,
        "precision": round(precision, 4),
        "recall": round(recall, 4),
        "f1": round(f1, 4),
        "fpr": round(fpr, 4),
        "tp": tp,
        "fp": fp,
        "fn": fn,
        "tn": tn,
    }


def export_verified_onnx(model: nn.Module, output_path: Path) -> tuple[str, float]:
    model_cpu = model.to("cpu").eval()
    dummy = torch.randn(1, 3, 224, 224, dtype=torch.float32)
    with torch.no_grad():
        expected = model_cpu(dummy).numpy()
    torch.onnx.export(
        model_cpu,
        dummy,
        str(output_path),
        input_names=["image"],
        output_names=["logits"],
        opset_version=17,
        do_constant_folding=True,
    )
    session = ort.InferenceSession(str(output_path), providers=["CPUExecutionProvider"])
    actual = session.run(None, {"image": dummy.numpy()})[0]
    max_diff = float(np.max(np.abs(expected - actual)))
    if max_diff > 1e-4:
        raise RuntimeError(f"ONNX parity check failed: max_abs_diff={max_diff:.6f}")
    return sha256_file(output_path), max_diff


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-dir", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--epochs", type=int, default=15)
    parser.add_argument("--batch-size", type=int, default=32)
    parser.add_argument("--lr", type=float, default=3e-4)
    parser.add_argument("--no-pretrained", action="store_true")
    parser.add_argument("--model-name", type=str, default="fire-verifier-mobilenetv3-v1.onnx")
    args = parser.parse_args()

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    LOGGER.info("Training Stage-2 fire verifier on device=%s", device)
    train_loader, val_loader, class_weights = build_loaders(args.data_dir, args.batch_size)
    total_batches = len(train_loader)
    LOGGER.info(
        "Loaded dataset: train=%d (%d batches), val=%d",
        len(train_loader.dataset),
        total_batches,
        len(val_loader.dataset),
    )
    model = build_model(pretrained=not args.no_pretrained).to(device)
    criterion = nn.CrossEntropyLoss(weight=class_weights.to(device))
    optimizer = torch.optim.AdamW(model.parameters(), lr=args.lr, weight_decay=1e-4)
    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=args.epochs)

    best_f1 = -1.0
    best_state: dict[str, Any] | None = None
    for epoch in range(1, args.epochs + 1):
        epoch_start = time.monotonic()
        model.train()
        running_loss = 0.0
        seen = 0
        for batch_idx, (images, labels) in enumerate(train_loader, start=1):
            optimizer.zero_grad()
            loss = criterion(model(images.to(device)), labels.to(device))
            loss.backward()
            optimizer.step()
            running_loss += float(loss.item()) * len(labels)
            seen += len(labels)
            if batch_idx % 20 == 0 or batch_idx == total_batches:
                LOGGER.info(
                    "Epoch %02d/%02d batch %d/%d loss=%.4f elapsed=%.1fs",
                    epoch,
                    args.epochs,
                    batch_idx,
                    total_batches,
                    running_loss / max(seen, 1),
                    time.monotonic() - epoch_start,
                )
        scheduler.step()
        val_probs, val_labels = evaluate_probabilities(model, val_loader, device)
        val_metrics = metrics_at_threshold(val_probs, val_labels, 0.55)
        LOGGER.info(
            "Epoch %02d/%02d DONE (%.1fs) loss=%.4f val_f1=%.4f val_prec=%.4f val_rec=%.4f val_fpr=%.4f",
            epoch,
            args.epochs,
            time.monotonic() - epoch_start,
            running_loss / max(len(train_loader.dataset), 1),
            val_metrics["f1"],
            val_metrics["precision"],
            val_metrics["recall"],
            val_metrics["fpr"],
        )
        if val_metrics["f1"] > best_f1:
            best_f1 = val_metrics["f1"]
            best_state = {k: v.cpu().clone() for k, v in model.state_dict().items()}

    if best_state is None:
        raise RuntimeError("No checkpoint produced during training")
    model.load_state_dict(best_state)
    val_probs, val_labels = evaluate_probabilities(model, val_loader, device)
    sweep = [
        metrics_at_threshold(val_probs, val_labels, round(t, 2))
        for t in np.arange(0.40, 0.85, 0.05)
    ]

    args.output_dir.mkdir(parents=True, exist_ok=True)
    onnx_path = args.output_dir / args.model_name
    digest, parity_diff = export_verified_onnx(model, onnx_path)
    report = {
        "modelFile": onnx_path.name,
        "sha256": digest,
        "parityMaxAbsDiff": parity_diff,
        "classes": CLASS_TO_INDEX,
        "thresholdSweep": sweep,
        "envSnippet": {
            "FIRE_VERIFIER_ENABLED": "true",
            "FIRE_VERIFIER_MODEL_PATH": f"models/{onnx_path.name}",
            "FIRE_VERIFIER_MODEL_SHA256": digest,
            "FIRE_VERIFIER_CONFIDENCE_THRESHOLD": "0.55",
        },
    }
    (args.output_dir / "verifier-report.json").write_text(
        json.dumps(report, indent=2), encoding="utf-8"
    )
    LOGGER.info("Exported ONNX=%s sha256=%s parity_diff=%.2e", onnx_path, digest, parity_diff)


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    main()
